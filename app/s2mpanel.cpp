// Default format of the endpoints

// Puts the chosen format on "Speak2Mic Speaker" and "Speak2Mic Microphone" as the Windows default
// format. Returns true when done (or impossible), false to try again later.
static bool ApplyEndpointFormats()
{
    const Settings& s = g_formatTarget;
    WORD bits = (WORD)(s.bits ? s.bits : 24);
    int done = 0, missing = 0, failed = 0, fellBack = 0;
    wchar_t lastErr[160] = L"";

    {
        for (int side = 0; side < 2; side++)
        {
            int i = FindCableDevice(side == 0);
            if (i < 0)
            {
                missing++;
                continue;
            }
            // The microphone may have its own channel count (0 = as the speaker).
            DWORD ch = side == 0 || !s.micChannels ? s.channels : s.micChannels;
            if (g_formatOnlyIfWrong)
            {
                DWORD r = 0;
                WORD b = 0, c = 0;
                // Bit depth is not compared: Windows may not accept 24/32 bits, then 16 bits is used.
                if (GetEndpointFormat(g_devs[i].id, &r, &b, &c) && r == s.rate && c <= ch)
                {
                    continue;   // still valid for the driver
                }
                AppLog(L"default format of \"%ls\" (%lu Hz %u bit %u ch) does not match the driver settings",
                       g_devs[i].name, r, b, c);
            }
            wchar_t err[160];
            bool ok = SetEndpointFormat(g_devs[i].id, s.rate, bits, (WORD)ch, err, 160);
            if (!ok && bits > 16)
            {
                // Windows does not always take 24/32-bit integer formats; 16 bits at the chosen rate
                // keeps the endpoint working.
                AppLog(L"default format of \"%ls\": %u bit refused (%ls), falling back to 16 bit", g_devs[i].name, bits, err);
                ok = SetEndpointFormat(g_devs[i].id, s.rate, 16, (WORD)ch, err, 160);
                if (ok) fellBack++;
            }
            if (ok)
            {
                DWORD r = 0;
                WORD b = 0, c = 0;
                GetEndpointFormat(g_devs[i].id, &r, &b, &c);
                AppLog(L"default format of \"%ls\": set %lu Hz %u bit %lu ch (%ls), now %lu Hz %u bit %u ch",
                       g_devs[i].name, s.rate, bits, ch, err, r, b, c);
                done++;
            }
            else
            {
                DWORD r = 0;
                WORD b = 0, c = 0;
                GetEndpointFormat(g_devs[i].id, &r, &b, &c);
                AppLog(L"default format of \"%ls\": %ls; now %lu Hz %u bit %u ch", g_devs[i].name, err, r, b, c);
                wcscpy(lastErr, err);
                failed++;
            }
        }
    }

    if (missing && --g_formatTries > 0)
    {
        return false;   // endpoints not back yet
    }
    AppLog(L"default formats: %d set, %d failed, %d endpoint(s) missing", done, failed, missing);
    DumpDriverLog(L"after applying settings");

    if (g_formatOnlyIfWrong && !done && !failed)
    {
        return true;    // startup check: nothing to fix
    }
    wchar_t t[300];
    if (failed)
        _snwprintf(t, 300, TR(L"Формат по умолчанию установлен не для всех устройств Speak2Mic: %ls"), lastErr);
    else if (missing && !done)
        _snwprintf(t, 300, TR(L"Устройства Speak2Mic не появились после перезапуска — формат по умолчанию не установлен."));
    else if (fellBack)
        _snwprintf(t, 300, TR(L"Настройки применены: %lu Гц, %lu кан. Windows не приняла %u бит — формат по умолчанию 16 бит."),
                   s.rate, s.channels, bits);
    else
        _snwprintf(t, 300, TR(L"Настройки применены: формат по умолчанию %lu Гц, %u бит, %lu кан."), s.rate, bits, s.channels);
    t[299] = 0;
    AddEvent(t);            // the result goes to the event list only
    ShowDriverStatus();     // the quality block shows what the driver runs with
    return true;
}

// ---------------------------------------------------------------------------
// Apply

// The microphone's volume and mute just before "Apply" restarts the device: Windows may bring back older values
// afterwards (a change made shortly before is not stored yet), so they are held once the endpoints are back.
static struct { bool ok; float db; bool mute; } g_levelBeforeApply;

static void OnApply()
{
    Settings s = SettingsFromControls();
    {
        int mic = FindCableDevice(false);
        float mn = 0, mx = 0;
        g_levelBeforeApply.ok = mic >= 0 && GetEndpointVolumeDb(g_devs[mic].id, &g_levelBeforeApply.db, &mn, &mx) &&
                                GetEndpointMute(g_devs[mic].id, &g_levelBeforeApply.mute);
    }
    // The cable devices disappear during the restart: release them first.
    StopTest();
    StopMusic();
    StopMeters();
    SetText(IDC_SETTINGS_STATUS, TR(L"Применение настроек, устройство перезапускается…"));
    UpdateWindow(g_wnd);

    MarkDriverLog();
    AppLog(L"apply requested: rate=%lu channels=%lu bits=%lu latency=%lu (elevated=%d)",
           s.rate, s.channels, s.bits, s.latency, (int)g_elevated);
    AppLog(L"apply requested: microphone channels %lu (0 = as the speaker)", s.micChannels);
    int rc = g_elevated ? ApplySettings(s) : ApplyElevated(g_wnd, s);
    AppLog(L"apply finished: code %d", rc);
    const wchar_t* msg = nullptr;
    switch (rc)
    {
    case 0:  msg = nullptr; break;
    case -1: msg = TR(L"Нужны права администратора: запрос был отклонён."); break;
    case 2:  msg = TR(L"Драйвер Speak2Mic не установлен."); break;
    case 3:  msg = TR(L"Настройки сохранены, но устройство Speak2Mic не найдено: применятся после его установки."); break;
    case 5:  msg = TR(L"Настройки сохранены. Windows не смогла перезапустить устройство на ходу — перезагрузите компьютер."); break;
    default: msg = TR(L"Настройки сохранены, но перезапустить устройство не удалось: перезагрузите компьютер."); break;
    }

    g_driverInstalled = ReadSettings(&g_settings);
    ShowDriverStatus();
    if (msg) AddEvent(msg);     // shown in the event list; the quality block keeps the driver status

    // Give Windows a moment to re-create the endpoints, then pick them up again and set their
    // default format (Windows keeps the old one otherwise).
    SetTimer(g_wnd, TIMER_REFRESH, 2500, nullptr);
    if (rc == 0 || rc == 3)
    {
        g_formatTarget = s;
        g_formatTries = 8;
        g_formatOnlyIfWrong = false;
    }
}

