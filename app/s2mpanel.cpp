// ---------------------------------------------------------------------------
// Reset everything

// Signal quality -> preset "Standard" (device restart like "Apply" if needed), device names -> defaults.
// The interface language is kept.
static void OnResetAll()
{
    if (MessageBoxW(g_wnd, TR(L"Сбросить все настройки Speak2Mic к стандартным?\n\nКачество сигнала — пресет «Стандарт», имена устройств — по умолчанию."),
                    L"Speak2Mic", MB_YESNO | MB_ICONQUESTION) != IDYES)
        return;
    AppLog(L"reset all settings requested");

    // Names first: the device restart below would otherwise make the panel wait for the endpoints.
    for (int side = 0; side < 2; side++)
    {
        SaveName(side, kDefaultName[side]);
        int i = FindCableDevice(side == 0);
        if (i >= 0 && wcscmp(g_devs[i].desc, kDefaultName[side]) != 0) RenameSide(side, kDefaultName[side], true);
        g_updatingControls = true;
        SetWindowTextW(Ctl(side == 0 ? IDC_SPKNAME : IDC_MICNAME), kDefaultName[side]);
        g_updatingControls = false;
        g_shownName[side][0] = 0;
    }

    Settings standard;
    standard.rate = 48000;
    standard.channels = 2;
    standard.bits = 16;
    standard.latency = 30;
    standard.micChannels = 1;
    ShowSettings(standard);
    int mic = FindCableDevice(false);
    if (mic >= 0)
    {
        SetEndpointVolumeDb(g_devs[mic].id, 0.0f);     // 100 % = unity gain (Windows' own "100 %" is +9.56 dB)
        SaveMicVolume(0.0f);
        SetEndpointMute(g_devs[mic].id, false);
    }
    g_micVolShown = -2;
    g_micMuteShown = -2;

    bool qualityChanges = g_driverInstalled &&
        (g_settings.rate != standard.rate || g_settings.channels != standard.channels ||
         g_settings.bits != standard.bits || g_settings.latency != standard.latency ||
         g_settings.micChannels != standard.micChannels);

    AddEvent( TR(L"Все настройки сброшены к стандартным."));
    if (qualityChanges)
        OnApply();
    else
        RefreshDevices();
}

