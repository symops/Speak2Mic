static bool ReadSettings(Settings* s)
{
    s->rate = 48000; s->channels = 2; s->bits = 16; s->latency = 30;   // preset "Standard"
    s->micChannels = 1;     // mono microphone by default (all presets)
    HKEY key;
    if (RegOpenKeyExW(HKEY_LOCAL_MACHINE, S2M_PARAMS_KEY, 0, KEY_READ, &key) != ERROR_SUCCESS)
    {
        return false;
    }
    struct { const wchar_t* name; DWORD* value; } items[] = {
        { L"SampleRate", &s->rate }, { L"Channels", &s->channels }, { L"MicChannels", &s->micChannels },
        { L"BitsPerSample", &s->bits }, { L"LatencyMs", &s->latency } };
    for (auto& it : items)
    {
        DWORD v = 0, size = sizeof(v), type = 0;
        if (RegQueryValueExW(key, it.name, nullptr, &type, (BYTE*)&v, &size) == ERROR_SUCCESS && type == REG_DWORD)
        {
            *it.value = v;
        }
    }
    RegCloseKey(key);
    return true;
}

// Exit codes of "s2mpanel --apply": 0 ok, 2 driver not installed, 3 device not found, 4 restart failed,
// 5 a reboot is needed to finish.
static int ApplySettings(const Settings& s)
{
    HKEY key;
    if (RegOpenKeyExW(HKEY_LOCAL_MACHINE, S2M_PARAMS_KEY, 0, KEY_SET_VALUE, &key) != ERROR_SUCCESS)
    {
        AppLog(L"apply: driver settings key not found (driver not installed)");
        return 2;
    }
    struct { const wchar_t* name; DWORD value; } items[] = {
        { L"SampleRate", s.rate }, { L"Channels", s.channels }, { L"MicChannels", s.micChannels },
        { L"BitsPerSample", s.bits }, { L"LatencyMs", s.latency } };
    for (auto& it : items)
    {
        RegSetValueExW(key, it.name, 0, REG_DWORD, (const BYTE*)&it.value, sizeof(DWORD));
    }
    RegDeleteValueW(key, L"CableCount");   // left over from versions with several cables
    RegCloseKey(key);

    bool found = false, reboot = false;
    // audiodg.exe keeps Speak2Mic streams open (e.g. default device): stop Windows Audio meanwhile.
    AudioServices stopped;
    AudioStopServices(false, &stopped);
    bool ok = S2mRestartDevice(&found, &reboot);
    AudioStartServices(&stopped);
    if (found && ok && !reboot)
    {
        // leftover endpoint records (the first restart after an installation leaves the installation's pair)
        bool com = SUCCEEDED(CoInitializeEx(nullptr, COINIT_APARTMENTTHREADED));
        S2mCleanupOrphanEndpoints(8000);
        if (com) CoUninitialize();
    }
    int rc = !found ? 3 : (!ok ? 4 : (reboot ? 5 : 0));
    AppLog(L"apply: rate=%lu channels=%lu bits=%lu latency=%lu -> device %ls, result %d",
           s.rate, s.channels, s.bits, s.latency, found ? L"found" : L"NOT found", rc);
    AppLog(L"apply: microphone channels %lu (0 = as the speaker)", s.micChannels);
    return rc;
}

static bool IsElevated()
{
    HANDLE token = nullptr;
    TOKEN_ELEVATION el = {};
    DWORD size = 0;
    bool elevated = false;
    if (OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, &token))
    {
        if (GetTokenInformation(token, TokenElevation, &el, sizeof(el), &size))
        {
            elevated = el.TokenIsElevated != 0;
        }
        CloseHandle(token);
    }
    return elevated;
}

// Runs "s2mpanel --apply ..." elevated and returns its exit code (-1 if UAC was declined).
static int ApplyElevated(HWND hwnd, const Settings& s)
{
    wchar_t exe[MAX_PATH], args[128];
    GetModuleFileNameW(nullptr, exe, MAX_PATH);
    _snwprintf(args, 128, L"--apply %lu %lu %lu %lu %lu", s.rate, s.channels, s.bits, s.latency, s.micChannels);
    args[127] = 0;

    SHELLEXECUTEINFOW sei = {};
    sei.cbSize = sizeof(sei);
    sei.fMask = SEE_MASK_NOCLOSEPROCESS;
    sei.hwnd = hwnd;
    sei.lpVerb = L"runas";
    sei.lpFile = exe;
    sei.lpParameters = args;
    sei.nShow = SW_HIDE;
    if (!ShellExecuteExW(&sei) || !sei.hProcess)
    {
        return -1;
    }
    WaitForSingleObject(sei.hProcess, 60000);
    DWORD code = 4;
    GetExitCodeProcess(sei.hProcess, &code);
    CloseHandle(sei.hProcess);
    return (int)code;
}

