static bool NameHas(const wchar_t* name, const wchar_t* part)
{
    size_t n = wcslen(part);
    for (; *name; name++)
        if (_wcsnicmp(name, part, n) == 0) return true;
    return false;
}

// Our endpoints are recognized by their adapter ("Speak2Mic"), not by their name: the user may rename them.
static bool IsOurDevice(const AudioDevice& d)
{
    return d.adapter[0] ? _wcsicmp(d.adapter, L"Speak2Mic") == 0 : NameHas(d.name, L"(Speak2Mic)");
}

// The playback side of the cable (input = true, "Speak2Mic Speaker") or the microphone.
static int FindInList(const AudioDevice* list, int count, bool input)
{
    for (int i = 0; i < count; i++)
    {
        if (list[i].flow == (input ? eRender : eCapture) && IsOurDevice(list[i])) return i;
    }
    return -1;
}

static int FindCableDevice(bool input)
{
    return FindInList(g_devs, g_devCount, input);
}

