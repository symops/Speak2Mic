// ---------------------------------------------------------------------------
// Microphone volume (the Windows endpoint volume of "Speak2Mic Microphone", as in its "Levels" tab)

// The slider is the signal level in percent of amplitude: 100 % = 0 dB (the cable's signal unchanged),
// 50 % = -6 dB, up to 300 % = +9.5 dB of boost; 0 % = the endpoint's minimum (silence). The driver's volume
// node has exactly that range (-96..+9.56 dB), so Windows' own "100 %" is the panel's 300 %. Drivers before
// 1.0.272 had no node: Windows used -96..+30 dB software volume, and stronger gain set elsewhere shows its real
// percentage next to the slider (which then sits at 300 %).
static int g_micVolShown = -1;      // volume shown, in 0.1 dB steps (+ 100000 offset); -1 = no microphone
static int g_micMuteShown = -1;     // mute state shown, -1 = unknown

// The volume chosen in the panel (slider, import, reset) is remembered: Windows may put this microphone back
// to its maximum (its own "100 %") when the endpoint is (re)created, e.g. after a device restart.
static void SaveMicVolume(float db)
{
    HKEY key;
    if (RegCreateKeyExW(HKEY_CURRENT_USER, S2M_USER_KEY, 0, nullptr, 0, KEY_SET_VALUE, nullptr, &key, nullptr) != ERROR_SUCCESS)
        return;
    DWORD centi = (DWORD)(LONG)floorf(db * 100.0f + 0.5f);     // hundredths of a dB, signed
    RegSetValueExW(key, L"MicVolumeCentiDb", 0, REG_DWORD, (const BYTE*)&centi, sizeof(centi));
    RegCloseKey(key);
}

static float LoadMicVolume()
{
    DWORD centi = 0, size = sizeof(centi);
    if (RegGetValueW(HKEY_CURRENT_USER, S2M_USER_KEY, L"MicVolumeCentiDb", RRF_RT_REG_DWORD, nullptr, &centi, &size) != ERROR_SUCCESS)
        return 0.0f;            // nothing chosen yet: unity gain
    return (LONG)centi / 100.0f;
}

static int DbToPercent(float db)
{
    // The top step of the driver's volume node (+9.5625 dB on its 1/16 dB grid) is exactly 300 % (gain x3.0).
    if (db > 9.53f && db < 9.60f) return 300;
    int pct = (int)(100.0f * powf(10.0f, db / 20.0f) + 0.5f);
    return pct < 0 ? 0 : pct;
}

static void ShowMicVolumeValue(float db)
{
    wchar_t t[32];
    _snwprintf(t, 32, L"%d %%", DbToPercent(db));
    t[31] = 0;
    SetText(IDC_MICVOL_VALUE, t);
}

// Reads the current volume and mute state (they may also be changed in Sound settings) unless the user
// drags the slider.
static void SyncMicVolume()
{
    int i = FindCableDevice(false);
    float db = 0, mn = 0, mx = 0;
    bool ok = i >= 0 && GetEndpointVolumeDb(g_devs[i].id, &db, &mn, &mx);
    bool mute = false;
    bool muteOk = i >= 0 && GetEndpointMute(g_devs[i].id, &mute);
    EnableWindow(Ctl(IDC_MICVOL), ok);
    EnableWindow(Ctl(IDC_MICMUTE), muteOk);
    int muteKey = muteOk ? (mute ? 1 : 0) : -1;
    if (muteKey != g_micMuteShown)
    {
        g_micMuteShown = muteKey;
        SendMessageW(Ctl(IDC_MICMUTE), BM_SETCHECK, mute ? BST_CHECKED : BST_UNCHECKED, 0);
    }
    if (ok && mx > 20.0f && db >= mx - 0.05f)
    {
        // Old driver (software volume up to +30 dB) at Windows' maximum: the endpoint was reset (the panel never
        // goes above +9.5 dB). With the driver's volume node the maximum is the panel's own 300 %.
        float want = LoadMicVolume();
        if (want < mx - 0.05f && SetEndpointVolumeDb(g_devs[i].id, want))
        {
            AppLog(L"microphone volume was at the Windows maximum (%.1f dB): restored %.1f dB", db, want);
            GetEndpointVolumeDb(g_devs[i].id, &db, &mn, &mx);
        }
    }
    int key = ok ? 100000 + (int)floorf(db * 10.0f + 0.5f) : -1;
    if (key == g_micVolShown || GetCapture() == Ctl(IDC_MICVOL)) return;
    g_micVolShown = key;
    if (!ok)
    {
        SetText(IDC_MICVOL_VALUE, L"—");
        return;
    }
    int pct = DbToPercent(db);
    SendMessageW(Ctl(IDC_MICVOL), TBM_SETPOS, TRUE, pct > kMicMaxPercent ? kMicMaxPercent : pct);
    ShowMicVolumeValue(db);
}

static void OnMicVolumeSlider(int code)
{
    int i = FindCableDevice(false);
    if (i < 0) return;
    int pct = (int)SendMessageW(Ctl(IDC_MICVOL), TBM_GETPOS, 0, 0);
    // Dragging with the mouse snaps to 0, 100, 200 and 300 % within 5 % of them (the keyboard moves freely: arrow
    // keys step by 1 and would never get past a snap point).
    if (code == TB_THUMBTRACK || code == TB_THUMBPOSITION)
    {
        static const int snaps[4] = { 0, 100, 200, 300 };
        for (int s : snaps)
        {
            if (pct != s && abs(pct - s) <= 5)
            {
                pct = s;
                SendMessageW(Ctl(IDC_MICVOL), TBM_SETPOS, TRUE, pct);
                break;
            }
        }
    }
    float db = pct > 0 ? 20.0f * log10f(pct / 100.0f) : -200.0f;     // -200: clamped to the minimum
    if (SetEndpointVolumeDb(g_devs[i].id, db))
    {
        float now = 0, mn = 0, mx = 0;
        if (GetEndpointVolumeDb(g_devs[i].id, &now, &mn, &mx))
        {
            g_micVolShown = 100000 + (int)floorf(now * 10.0f + 0.5f);
            ShowMicVolumeValue(now);
        }
        SaveMicVolume(db < mn ? mn : db);
    }
}

