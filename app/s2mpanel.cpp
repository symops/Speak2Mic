// Driver log -> panel.log

static void MarkDriverLog()
{
    SYSTEMTIME t;
    GetLocalTime(&t);
    _snwprintf(g_driverLogMark, 32, L"%04u-%02u-%02u %02u:%02u:%02u.%03u", t.wYear, t.wMonth, t.wDay, t.wHour,
               t.wMinute, t.wSecond, t.wMilliseconds);
    g_driverLogMark[31] = 0;
}

// Copies the driver log lines written after g_driverLogMark into panel.log.
static void DumpDriverLog(const wchar_t* reason)
{
    DWORD size = 0;
    if (RegGetValueW(HKEY_LOCAL_MACHINE, S2M_PARAMS_KEY, L"DriverLog", RRF_RT_REG_SZ, nullptr, nullptr, &size) != ERROR_SUCCESS ||
        !size)
        return;
    wchar_t* text = (wchar_t*)HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, size + 2);
    if (!text) return;
    if (RegGetValueW(HKEY_LOCAL_MACHINE, S2M_PARAMS_KEY, L"DriverLog", RRF_RT_REG_SZ, nullptr, text, &size) == ERROR_SUCCESS)
    {
        AppLog(L"---- driver log since %ls (%ls) ----", g_driverLogMark, reason);
        for (wchar_t* line = text; *line;)
        {
            wchar_t* end = line;
            while (*end && *end != L'\r' && *end != L'\n') end++;
            wchar_t saved = *end;
            *end = 0;
            if (wcslen(line) >= 23 && wcsncmp(line, g_driverLogMark, 23) > 0)
            {
                AppLog(L"[driver] %ls", line);
                wcsncpy(g_driverLogMark, line, 23);     // next dump starts after this line
                g_driverLogMark[23] = 0;
            }
            *end = saved;
            while (*end == L'\r' || *end == L'\n') end++;
            line = end;
        }
    }
    HeapFree(GetProcessHeap(), 0, text);
}

